"""Create the Sidro 1.0 release asset including its updater."""
import os
from pathlib import Path
import tempfile
import zipfile
from bundle_release_materials import verify_release_materials

BLOCKED = {
    'user_data', '.git', '.aws', '.codex', '.wrangler', 'services',
    '__pycache__',
    'du.bin', 'daily_usage.bin', 'patreon_auth.bin', 'support_reminder.json', 'account_state.json',
    'app_settings.json', 'sidro-settings-backup.json',
    'entitlement_private_key.b64', 'token_encryption_key.b64',
}
ROOT_FILES = {
    'sidro.exe', 'sidroupdater.exe', 'readme.md', 'license', '.env.example',
    'app_settings.example.json', 'release_requirements.md',
    'third_party_notices.md', 'dependency_baseline.md',
    'dependency_inventory.json', 'requirements.txt', 'requirements-release.lock',
    'requirements-windowsocr.txt', 'requirements-rapidocr-test.txt',
    'requirements-paddleocr-test.txt', 'release_manifest.json',
}


def release_files(build: Path) -> list[Path]:
    """Reject contaminated output before opening or replacing an existing ZIP."""
    files = []
    for path in sorted(build.rglob('*')):
        relative = path.relative_to(build)
        parts = [part.lower() for part in relative.parts]
        if path.is_symlink() or path.is_junction():
            raise RuntimeError(f'Release cannot contain links: {relative}')
        if any(part in BLOCKED or part == '.env' or
               (part.startswith(('.env.', '.dev.vars')) and part != '.env.example')
               for part in parts):
            raise RuntimeError(f'Private/development file in release: {relative}')
        if parts[0] not in {'_internal', 'licenses', 'sources'} and (
                len(parts) != 1 or parts[0] not in ROOT_FILES):
            raise RuntimeError(f'Unreviewed release component: {relative}')
        if path.is_file():
            if path.suffix.lower() in {'.pyc', '.pyo'}:
                raise RuntimeError(f'Generated bytecode cache in release: {relative}')
            if path.suffix.lower() in {'.pfx', '.p12'}:
                raise RuntimeError(f'Private certificate container in release: {relative}')
            files.append(path)
    return files


def make_release_zip(build: Path, destination: Path) -> None:
    for required in ('Sidro.exe', 'SidroUpdater.exe', '_internal'):
        if not (build / required).exists():
            raise RuntimeError(f'Missing release component: {required}')
    verify_release_materials(build)
    files = release_files(build)
    descriptor, temporary = tempfile.mkstemp(prefix=destination.name + '.', suffix='.tmp', dir=destination.parent)
    os.close(descriptor)
    try:
        with zipfile.ZipFile(temporary, 'w', zipfile.ZIP_DEFLATED) as archive:
            for path in files:
                archive.write(path, str(Path('Sidro') / path.relative_to(build)))
        with zipfile.ZipFile(temporary) as archive:
            if archive.testzip() is not None:
                raise RuntimeError('Release ZIP integrity verification failed.')
        os.replace(temporary, destination)
    finally:
        Path(temporary).unlink(missing_ok=True)


if __name__ == '__main__':
    root = Path(__file__).resolve().parents[1]
    make_release_zip(root / 'dist/Sidro', root / 'dist/Sidro-windows-v1.0.zip')
    print('Created dist/Sidro-windows-v1.0.zip')
